import { jsPDF } from 'jspdf';

export interface DemoDocOption {
  id: string;
  title: string;
  subject: string;
  description: string;
  generate: () => ArrayBuffer;
}

export function generateBiologyDemoPdf(): ArrayBuffer {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  // Page 1
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(24, 43, 73);
  doc.text('Cellular Respiration & ATP Production', 40, 55);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text('Advanced Biology Study Series • High-Yield Revision Guide', 40, 75);

  // Section 1
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(30, 58, 138);
  doc.text('1. Overview of Cellular Respiration', 40, 110);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  const p1 =
    'Cellular respiration is the fundamental metabolic process through which eukaryotic cells break down biochemical nutrients, primarily glucose, to harvest usable chemical energy in the form of adenosine triphosphate (ATP). The overall chemical equation is C6H12O6 + 6O2 -> 6CO2 + 6H2O + approximately 30 to 32 ATP molecules.';
  const splitP1 = doc.splitTextToSize(p1, pageWidth - 80);
  doc.text(splitP1, 40, 130);

  const p2 =
    'This multi-step catabolic pathway is divided into three major stages: Glycolysis occurring in the cytoplasm, the Citric Acid Cycle (Krebs cycle) occurring in the mitochondrial matrix, and Oxidative Phosphorylation across the inner mitochondrial membrane.';
  const splitP2 = doc.splitTextToSize(p2, pageWidth - 80);
  doc.text(splitP2, 40, 185);

  // Section 2
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(30, 58, 138);
  doc.text('2. Glycolysis: The Cytoplasmic Phase', 40, 240);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  const p3 =
    'Glycolysis is an anaerobic pathway that converts one molecule of glucose (6 carbons) into two molecules of pyruvate (3 carbons). During the energy investment phase, 2 ATP molecules are consumed to phosphorylate glucose, while during the energy payoff phase, 4 ATP and 2 NADH molecules are generated by substrate-level phosphorylation, yielding a net gain of 2 ATP.';
  const splitP3 = doc.splitTextToSize(p3, pageWidth - 80);
  doc.text(splitP3, 40, 260);

  const p4 =
    'Because glycolysis does not require oxygen, it occurs universally across both aerobic and anaerobic organisms. If oxygen is absent in muscle tissue or yeast, pyruvate enters fermentation to regenerate NAD+ so glycolysis can continue.';
  const splitP4 = doc.splitTextToSize(p4, pageWidth - 80);
  doc.text(splitP4, 40, 325);

  // Section 3
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(30, 58, 138);
  doc.text('3. The Citric Acid Cycle (Krebs Cycle)', 40, 385);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  const p5 =
    'In the presence of oxygen, pyruvate is actively transported into the mitochondrial matrix and converted into acetyl-CoA by the pyruvate dehydrogenase complex. This transition reaction releases carbon dioxide and produces one NADH per pyruvate.';
  const splitP5 = doc.splitTextToSize(p5, pageWidth - 80);
  doc.text(splitP5, 40, 405);

  const p6 =
    'During each turn of the Krebs cycle, acetyl-CoA combines with oxaloacetate to form citrate. For every molecule of glucose, two cycles run, producing 4 CO2, 6 NADH, 2 FADH2, and 2 ATP (or GTP). These electron carriers carry high-energy electrons directly to the electron transport chain.';
  const splitP6 = doc.splitTextToSize(p6, pageWidth - 80);
  doc.text(splitP6, 40, 465);

  // Section 4
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(30, 58, 138);
  doc.text('4. Oxidative Phosphorylation & Chemiosmosis', 40, 535);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  const p7 =
    'Oxidative phosphorylation is responsible for producing the vast majority of cellular ATP. Electrons donated by NADH and FADH2 pass through four protein complexes (I to IV) embedded in the inner mitochondrial cristae. This movement powers proton pumps that drive H+ into the intermembrane space, building an electrochemical proton gradient.';
  const splitP7 = doc.splitTextToSize(p7, pageWidth - 80);
  doc.text(splitP7, 40, 555);

  const p8 =
    'According to Peter Mitchell chemiosmotic hypothesis, protons flow back into the matrix through ATP Synthase, driving rotary catalysis that condenses ADP and inorganic phosphate into ATP. Oxygen serves as the final electron acceptor, binding protons to form water.';
  const splitP8 = doc.splitTextToSize(p8, pageWidth - 80);
  doc.text(splitP8, 40, 625);

  // Footer
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text('Smart PDF Analyzer • Page 1 of 1', pageWidth / 2 - 60, 780);

  return doc.output('arraybuffer');
}

export function generateComputerScienceDemoPdf(): ArrayBuffer {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  // Page 1
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(15, 23, 42);
  doc.text('Operating Systems: Virtual Memory & Paging', 40, 55);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text('Computer Science Core Curriculum • Operating Systems Architecture', 40, 75);

  // Section 1
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(14, 116, 144);
  doc.text('1. Purpose of Virtual Memory', 40, 110);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  const p1 =
    'Virtual memory is a memory management technique that provides an idealized abstraction of the storage resources actually available on a given machine. It enables programs to run in contiguous address spaces larger than physical random access memory (RAM), while isolating processes from each other to enforce strict memory protection.';
  const splitP1 = doc.splitTextToSize(p1, pageWidth - 80);
  doc.text(splitP1, 40, 130);

  const p2 =
    'The Memory Management Unit (MMU) is a dedicated hardware component inside the CPU that performs address translation, dynamically converting virtual addresses generated by program code into physical hardware addresses in RAM.';
  const splitP2 = doc.splitTextToSize(p2, pageWidth - 80);
  doc.text(splitP2, 40, 185);

  // Section 2
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(14, 116, 144);
  doc.text('2. Paging Mechanism and Page Tables', 40, 240);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  const p3 =
    'In paging, virtual memory is partitioned into fixed-size blocks called pages, typically 4 Kilobytes in modern x86-64 architectures. Physical memory is similarly divided into matching fixed-size blocks called page frames. A process virtual page can reside in any physical page frame anywhere in RAM.';
  const splitP3 = doc.splitTextToSize(p3, pageWidth - 80);
  doc.text(splitP3, 40, 260);

  const p4 =
    'Every process maintains a page table containing Page Table Entries (PTEs). Each entry records the physical frame number, a valid bit indicating if the page is currently in RAM, read-write permissions, and a dirty bit indicating if data was modified.';
  const splitP4 = doc.splitTextToSize(p4, pageWidth - 80);
  doc.text(splitP4, 40, 325);

  // Section 3
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(14, 116, 144);
  doc.text('3. Page Faults and Swapping', 40, 385);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  const p5 =
    'When a running process attempts to access a virtual page whose valid bit is set to 0, the MMU hardware triggers a Page Fault trap to the operating system kernel. The CPU saves state and transfers control to the page fault handler.';
  const splitP5 = doc.splitTextToSize(p5, pageWidth - 80);
  doc.text(splitP5, 40, 405);

  const p6 =
    'The kernel locates the desired page in secondary backing storage (SSD or swap partition), finds a free physical frame in RAM, reads the disk block into memory, updates the page table entry, and restarts the instruction that caused the fault.';
  const splitP6 = doc.splitTextToSize(p6, pageWidth - 80);
  doc.text(splitP6, 40, 465);

  // Section 4
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(14, 116, 144);
  doc.text('4. Translation Lookaside Buffer (TLB)', 40, 535);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  const p7 =
    'Accessing a page table in RAM for every memory reference would halve overall system execution speed. To overcome this memory wall, CPUs utilize the Translation Lookaside Buffer (TLB), an ultra-fast hardware associative cache that stores the most recently translated virtual-to-physical mappings.';
  const splitP7 = doc.splitTextToSize(p7, pageWidth - 80);
  doc.text(splitP7, 40, 555);

  const p8 =
    'A TLB hit allows single-cycle translation. A TLB miss requires a multi-level page table walk in memory before caching the result. High spatial and temporal locality in application algorithms typically yields TLB hit rates exceeding 98%.';
  const splitP8 = doc.splitTextToSize(p8, pageWidth - 80);
  doc.text(splitP8, 40, 625);

  // Footer
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text('Smart PDF Analyzer • Page 1 of 1', pageWidth / 2 - 60, 780);

  return doc.output('arraybuffer');
}

